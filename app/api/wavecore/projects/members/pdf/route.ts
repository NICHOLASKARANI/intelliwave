export const dynamic = 'force-dynamic'

import { NextRequest, NextResponse } from 'next/server'
import { pool } from '@/lib/wavecore/db'
import { requireTenant } from '@/lib/wavecore/auth'
import { guardHR } from '@/lib/wavecore/guard'

export async function GET(request: NextRequest) {
  try {
    const session = await requireTenant(request)
    if (!session) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })
    const guard = await guardHR(request, 'HR_EXPORT')
    if (guard.deny) return guard.response!

    const orgId = session.organizationId
    const res = await pool.query(
      `SELECT m.*, p.title AS project_title FROM "ProjectMember" m
       LEFT JOIN "Project" p ON p.id = m."projectId" AND p."organizationId" = m."organizationId"
       WHERE m."organizationId" = $1 ORDER BY m."createdAt" ASC LIMIT 500`,
      [orgId]
    )
    const members = res.rows.map(m => ({ ...m, hourlyRate: Number(m.hourlyRate || 0), allocatedHours: Number(m.allocatedHours || 0) }))
    const total = members.length
    const totalHours = Math.round(members.reduce((s, m) => s + m.allocatedHours, 0))
    const avgRate = total > 0 ? Math.round(members.reduce((s, m) => s + m.hourlyRate, 0) / total) : 0
    const totalCost = Math.round(members.reduce((s, m) => s + m.hourlyRate * m.allocatedHours, 0))

    const rows = members.map((m, i) => `
      <tr>
        <td style="text-align:center;color:#6b7280">${i + 1}</td>
        <td><b>${m.employeeName || '—'}</b></td>
        <td>${m.project_title || '—'}</td>
        <td style="text-align:center">${m.role || 'MEMBER'}</td>
        <td style="text-align:right">${m.hourlyRate.toLocaleString()}</td>
        <td style="text-align:right">${m.allocatedHours}</td>
        <td style="text-align:right">${(m.hourlyRate * m.allocatedHours).toLocaleString()}</td>
      </tr>`).join('')

    const html = `<!DOCTYPE html><html><head><meta charset="utf-8"><title>Resource Planning Report</title>
<style>__STYLE__</style></head><body>
<div class="hdr">
  <div><div class="brand">WaveCore ERP</div><div class="brand-sub">Project Management · Resource Planning</div></div>
  <div class="doc-title"><h1>RESOURCES</h1><div class="num">${new Date().toLocaleDateString('en-GB')}</div></div>
</div>
<div class="stats">
  <div class="stat"><div class="stat-num">${total}</div><div class="stat-label">Members</div></div>
  <div class="stat"><div class="stat-num" style="color:#0d9488">${totalHours}</div><div class="stat-label">Allocated Hrs</div></div>
  <div class="stat"><div class="stat-num" style="color:#0891b2">${avgRate.toLocaleString()}</div><div class="stat-label">Avg Rate/hr</div></div>
  <div class="stat"><div class="stat-num" style="color:#16a34a">${totalCost.toLocaleString()}</div><div class="stat-label">Total Cost</div></div>
  <div class="stat"><div class="stat-num">${new Set(members.map(m => m.projectId)).size}</div><div class="stat-label">Projects</div></div>
  <div class="stat"><div class="stat-num">${new Date().toLocaleDateString('en-GB')}</div><div class="stat-label">Generated</div></div>
</div>
<div class="section-title">Team Members (${total})</div>
<table>
  <thead><tr><th style="text-align:center">#</th><th>Member</th><th>Project</th><th style="text-align:center">Role</th><th style="text-align:right">Rate/hr</th><th style="text-align:right">Hours</th><th style="text-align:right">Cost</th></tr></thead>
  <tbody>${rows || '<tr><td colspan="7" style="text-align:center;color:#9ca3af;padding:24px">No members yet</td></tr>'}</tbody>
</table>
<div class="footer"><p>Generated by WaveCore ERP · © ${new Date().getFullYear()} IntelliWavve</p></div>
<script>window.onload = function(){ setTimeout(function(){ window.print(); }, 400); };</script>
</body></html>`.replace('__STYLE__', `  @page { size: A4 landscape; margin: 10mm; }
  body { font-family: 'Segoe UI', Arial, sans-serif; color: #111827; margin: 0; }
  .hdr { display: flex; justify-content: space-between; border-bottom: 4px solid #0d9488; padding-bottom: 16px; margin-bottom: 20px; }
  .brand { font-size: 28px; font-weight: 800; color: #0d9488; }
  .brand-sub { font-size: 12px; color: #6b7280; margin-top: 2px; }
  .doc-title h1 { font-size: 22px; margin: 0; }
  .doc-title .num { font-family: 'Courier New', monospace; font-size: 14px; color: #0d9488; margin-top: 4px; font-weight: 700; }
  .stats { display: grid; grid-template-columns: repeat(6, 1fr); gap: 10px; margin-bottom: 20px; }
  .stat { padding: 12px; border: 2px solid #e5e7eb; border-radius: 10px; text-align: center; }
  .stat-num { font-size: 20px; font-weight: 800; }
  .stat-label { font-size: 9px; text-transform: uppercase; color: #6b7280; letter-spacing: 0.5px; font-weight: 700; margin-top: 3px; }
  .section-title { font-size: 13px; font-weight: 800; color: #0d9488; text-transform: uppercase; letter-spacing: 0.6px; margin: 18px 0 8px; padding-bottom: 4px; border-bottom: 2px solid #ccfbf1; }
  table { width: 100%; border-collapse: collapse; font-size: 10px; }
  thead th { background: #0d9488; color: white; text-align: left; padding: 8px 6px; font-size: 9px; text-transform: uppercase; }
  tbody td { padding: 7px 6px; border-bottom: 1px solid #f3f4f6; }
  tbody tr:nth-child(even) { background: #f0fdfa; }
  .footer { margin-top: 24px; text-align: center; color: #9ca3af; font-size: 10px; border-top: 1px solid #e5e7eb; padding-top: 12px; }`)

    return new NextResponse(html, { headers: { 'Content-Type': 'text/html; charset=utf-8' } })
  } catch (error) {
    console.error('Resources PDF error:', error)
    return NextResponse.json({ error: 'Failed to generate report' }, { status: 500 })
  }
}