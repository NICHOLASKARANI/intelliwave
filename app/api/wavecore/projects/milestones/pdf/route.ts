export const dynamic = 'force-dynamic'

import { NextRequest, NextResponse } from 'next/server'
import { pool } from '@/lib/wavecore/db'
import { requireTenant } from '@/lib/wavecore/auth'
import { guardHR } from '@/lib/wavecore/guard'
import { getBranding, brandingHeaderHtml } from '@/lib/wavecore/report-branding'

export async function GET(request: NextRequest) {
  try {
    const session = await requireTenant(request)
    if (!session) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })
    const guard = await guardHR(request, 'HR_EXPORT')
    if (guard.deny) return guard.response!
    const branding = await getBranding(session.organizationId)

    const orgId = session.organizationId
    const msRes = await pool.query(
      `SELECT m.*, p.title AS project_title FROM "Milestone" m
       LEFT JOIN "Project" p ON p.id = m."projectId" AND p."organizationId" = m."organizationId"
       WHERE m."organizationId" = $1 ORDER BY m."dueDate" ASC LIMIT 500`,
      [orgId]
    )
    const milestones = msRes.rows.map(m => {
      const due = m.dueDate ? new Date(m.dueDate) : null
      const now = new Date()
      return { ...m, isOverdue: !m.completed && due && due < now, daysUntil: due ? Math.ceil((due.getTime() - now.getTime()) / (1000 * 60 * 60 * 24)) : null }
    })
    const total = milestones.length
    const done = milestones.filter(m => m.completed).length
    const overdue = milestones.filter(m => m.isOverdue).length
    const pending = total - done

    const rows = milestones.map((m, i) => `
      <tr>
        <td style="text-align:center;color:#6b7280">${i + 1}</td>
        <td><b>${m.title}</b></td>
        <td>${m.project_title || '—'}</td>
        <td style="text-align:center">${m.dueDate ? new Date(m.dueDate).toLocaleDateString('en-GB') : '—'}</td>
        <td style="text-align:center">${m.completed ? '✔ Done' : (m.isOverdue ? '⚠ OVERDUE' : 'Pending')}</td>
        <td style="text-align:center">${m.completed ? '—' : (m.daysUntil != null ? m.daysUntil + 'd' : '—')}</td>
      </tr>`).join('')

    const html = `<!DOCTYPE html><html><head><meta charset="utf-8"><title>Milestones Report</title>
<style>
__STYLE__
</style></head><body>
<div class="hdr">
  ${brandingHeaderHtml(branding, { subtitle: 'Project Management · Milestones Report' })}
  <div class="doc-title"><h1>MILESTONES</h1><div class="num">${new Date().toLocaleDateString('en-GB')}</div></div>
</div>
<div class="stats">
  <div class="stat"><div class="stat-num">${total}</div><div class="stat-label">Total</div></div>
  <div class="stat"><div class="stat-num" style="color:#16a34a">${done}</div><div class="stat-label">Completed</div></div>
  <div class="stat"><div class="stat-num" style="color:#ca8a04">${pending}</div><div class="stat-label">Pending</div></div>
  <div class="stat"><div class="stat-num" style="color:${overdue > 0 ? '#dc2626' : '#6b7280'}">${overdue}</div><div class="stat-label">Overdue</div></div>
  <div class="stat"><div class="stat-num" style="color:#0d9488">${total > 0 ? Math.round((done / total) * 100) : 0}%</div><div class="stat-label">Completion</div></div>
  <div class="stat"><div class="stat-num" style="color:#0d9488">${new Date().toLocaleDateString('en-GB')}</div><div class="stat-label">Generated</div></div>
</div>
<div class="section-title">Milestones (${total})</div>
<table>
  <thead><tr><th style="text-align:center">#</th><th>Milestone</th><th>Project</th><th style="text-align:center">Due</th><th style="text-align:center">Status</th><th style="text-align:center">Days</th></tr></thead>
  <tbody>${rows || '<tr><td colspan="6" style="text-align:center;color:#9ca3af;padding:24px">No milestones yet</td></tr>'}</tbody>
</table>
<div class="footer"><p>Generated by WaveCore ERP · © ${new Date().getFullYear()} IntelliWavve</p></div>
<script>window.onload = function(){ setTimeout(function(){ window.print(); }, 400); };</script>
</body></html>`.replace('__STYLE__', `  @page { size: A4 landscape; margin: 10mm; }
  body { font-family: 'Segoe UI', Arial, sans-serif; color: #111827; margin: 0; }
  .hdr { display: flex; justify-content: space-between; border-bottom: 4px solid #0d9488; padding-bottom: 16px; margin-bottom: 20px; }
  .brand { font-size: 28px; font-weight: 800; color: #0d9488; }
  .brand-sub { font-size: 12px; color: #6b7280; margin-top: 2px; }
  .doc-title h1 { font-size: 22px; margin: 0; }
  .doc-title .num { font-family: 'Courier New', monospace; font-size: 14px; color: #0d9488; margin-top: 4px; font-weight: 700; }
  .stats { display: grid; grid-template-columns: repeat(6, 1fr); gap: 10px; margin-bottom: 20px; }
  .stat { padding: 12px; border: 2px solid #e5e7eb; border-radius: 10px; text-align: center; }
  .stat-num { font-size: 20px; font-weight: 800; }
  .stat-label { font-size: 9px; text-transform: uppercase; color: #6b7280; letter-spacing: 0.5px; font-weight: 700; margin-top: 3px; }
  .section-title { font-size: 13px; font-weight: 800; color: #0d9488; text-transform: uppercase; letter-spacing: 0.6px; margin: 18px 0 8px; padding-bottom: 4px; border-bottom: 2px solid #ccfbf1; }
  table { width: 100%; border-collapse: collapse; font-size: 10px; }
  thead th { background: #0d9488; color: white; text-align: left; padding: 8px 6px; font-size: 9px; text-transform: uppercase; }
  tbody td { padding: 7px 6px; border-bottom: 1px solid #f3f4f6; }
  tbody tr:nth-child(even) { background: #f0fdfa; }
  .footer { margin-top: 24px; text-align: center; color: #9ca3af; font-size: 10px; border-top: 1px solid #e5e7eb; padding-top: 12px; }`)

    return new NextResponse(html, { headers: { 'Content-Type': 'text/html; charset=utf-8' } })
  } catch (error) {
    console.error('Milestones PDF error:', error)
    return NextResponse.json({ error: 'Failed to generate report' }, { status: 500 })
  }
}
